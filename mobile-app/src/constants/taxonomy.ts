export function formatExternalUrl(url?: string): string {
  if (!url) return ''
  const trimmed = url.trim()
  if (!trimmed) return ''
  if (/^https?:\/\//i.test(trimmed)) return trimmed
  return `https://${trimmed}`
}

export function isReklamIlani(tender: any): boolean {
  if (!tender) return false
  const fType = (tender.formType || tender.customFields?.formType || '').toString().toUpperCase()
  const ihaleYonu = (tender.ihaleYonu || '').toString().toLowerCase()
  const tur = (tender.tur || '').toString().toLowerCase()
  const kat = (tender.kategori || '').toString().toLowerCase()
  return (
    fType === 'REKLAM_ILANI' ||
    fType === 'REKLAM' ||
    ihaleYonu === 'reklam' ||
    tur.includes('reklam') ||
    kat.includes('reklam')
  )
}

export function getDigerCustomBadge(tender: any): string | null {
  if (!tender) return null
  const cf = tender.customFields || {}
  const raw = cf.altKategoriDiger || cf.anaKategoriDiger || cf.digerMetni || cf.altKategori
  if (raw && typeof raw === 'string') {
    const trimmed = raw.trim()
    if (trimmed && trimmed.toUpperCase() !== 'DİĞER' && trimmed.toUpperCase() !== 'DIGER') {
      return trimmed
    }
  }
  return null
}
